"""Extract the constant tables used by Sony's ATRAC3 'algorithm 0' encoder (LP4 / 105 kbps)
from private/psp_at3tool.exe and write spec/reference/lp4_tables.py.

Every table is written with the virtual address it was read from so that the reference model
stays traceable."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from peutil import f32s, i32s, u32s

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'spec', 'reference', 'lp4_tables.py')


def fl(vals):
    return '[' + ', '.join(repr(float(v)) for v in vals) + ']'


def ints(vals):
    return '[' + ', '.join(str(int(v)) for v in vals) + ']'


def main():
    L = []
    w = L.append
    w('"""Constant tables of the Sony ATRAC3 \'algorithm 0\' encoder (MiniDisc LP4 66 kbps JS, 105 kbps).')
    w('')
    w('Generated by tools/extract_lp4_tables.py from psp_at3tool.exe - do not edit.')
    w('All float values are IEEE single precision (they are exactly representable as float32).')
    w('Addresses are virtual addresses in psp_at3tool.exe."""')
    w('')
    w('# Encoder settings per mode (0x48cf74..0x48d030): index 0 = 66 kbps JS (LP4),')
    w('# index 2 = 105 kbps stereo.  Other rows exist in the table but are not reachable from the CLI.')
    names = [('IS_JOINT', 0x48cf74), ('CHANNEL_MODE', 0x48cf8c), ('BITRATE', 0x48cfa4), ('BLOCK_ALIGN', 0x48cfbc),
             ('CHANNEL_BYTES0', 0x48cfd4), ('CHANNEL_BYTES1', 0x48cfec), ('CHANNEL_HERTZ0', 0x48d004),
             ('CHANNEL_HERTZ1', 0x48d01c)]
    for n, a in names:
        w('%s = %s   # 0x%x' % (n, ints(i32s(a, 6)), a))
    w('')
    w('# Subband (quantisation unit) layout [0x48b590, 0x48cc80]')
    w('SB_START = %s' % ints(i32s(0x48b590, 33)))
    w('SB_WIDTH = %s' % ints(i32s(0x48cc80, 32)))
    w('')
    w('# QMF analysis filter: per-lane coefficient vectors exactly as stored (0x48bfd0..0x48c20f).')
    w('# Stage 1 (two-band split, 2 outputs per lane pair): 12 vectors QMF1[k] at 0x48bfd0 + 16k.')
    w('QMF1 = [')
    for a in range(0x48bfd0, 0x48c090, 16):
        w('    %s,  # 0x%x' % (fl(f32s(a, 4)), a))
    w(']')
    w('# Stage 2 (second split of both halves): 24 vectors QMF2[k] at 0x48c090 + 16k.')
    w('QMF2 = [')
    for a in range(0x48c090, 0x48c210, 16):
        w('    %s,  # 0x%x' % (fl(f32s(a, 4)), a))
    w(']')
    w('')
    w('# MDCT (0x435380): input permutation [bit reversal-like, 0x4be9e8], pre-twiddle/window vectors')
    w('# (4 floats per index, 0x48c280), butterfly twiddles (0x48ca80), final butterfly constant (0x48bfa0)')
    w('MDCT_PERM = %s' % ints(i32s(0x4be9e8, 128)))
    w('MDCT_TW = [')
    for k in range(128):
        w('    %s,' % fl(f32s(0x48c280 + 16 * k, 4)))
    w(']')
    w('MDCT_FFT_TW = %s' % fl(f32s(0x48ca80, 127)))
    w('MDCT_SQRT_HALF = %r   # 0x48bfa0' % float(f32s(0x48bfa0, 1)[0]))
    w('')
    w('# Gain control: 2**(level-4) (0x48be48) and the ramp table used to build 2**(v/8-4) (0x48be88)')
    w('GAIN_POW2 = %s' % fl(f32s(0x48be48, 16)))
    w('GAIN_RAMP_BITS = [%s]' % ', '.join('0x%08x' % v for v in u32s(0x48be88, 8)))
    w('')
    w('# Joint stereo [0x48bea8, 0x48bec0]')
    w('CHSW_TABLE = %s' % fl(f32s(0x48bea8, 5)))
    w('CHWT_TABLE = %s' % fl(f32s(0x48bec0, 24)))
    w('')
    w('# Scale factor values 2**((i-15)/3) as float32 bit patterns [0x4bebe8]')
    w('SF_BITS = [%s]' % ', '.join('0x%08x' % v for v in u32s(0x4bebe8, 64)))
    w('# Quantiser scale numerators, indexed 3*sel - sf%%3, float32 bit patterns (0x48b614)')
    w('QSCALE_BITS = [%s]' % ', '.join('0x%08x' % v for v in u32s(0x48b614, 22)))
    w('# Index masks for (rounded value & mask) per selector (0x48b664; entries 0,1 unused)')
    w('QMASK = %s' % ints(u32s(0x48b664, 8)))
    w('')
    w('# Bit allocation tables (0x48cd00..0x48cee0)')
    w('MIN_SFSUM = %s   # 0x48cd00' % ints(i32s(0x48cd00, 32)))
    w('ZERO_LEN2 = %s   # 0x48cd7c: 2 x (length of the code for 0) per selector, sel 1 per value' % ints(i32s(0x48cd7c, 8)))
    w('STEP_COST = %s   # 0x48cd80 (index sel, sel < 7 used)' % ints(i32s(0x48cd80, 8)))
    w('EST_SAVE = %s   # 0x48cd98 (index sel 1..7)' % ints(i32s(0x48cd98, 8)))
    w('EST_BITS = %s   # 0x48cdb4 (index sel 1..7; tenths of a bit per coefficient)' % ints(i32s(0x48cdb4, 8)))
    w('EST_THR = %s   # 0x48cdd0 (index sel 1..7)' % ints(i32s(0x48cdd0, 8)))
    w('TONE_PENALTY = %s   # 0x48cf60' % ints(i32s(0x48cf60, 5)))
    w('TONE_SF_OFFSET = %s   # 0x48cee0, index sel_class + 8*qmf_band' % ints(i32s(0x48cee0, 32)))
    w('SEL1_LEN = %s   # 0x48ce60: VLC bits of 4 selector-1 values by nonzero pattern' % ints(i32s(0x48ce60, 16)))
    w('')
    w('# VLC / CLC code tables used by the encoder: VLC[(mode, sel)][index] = (code, length).')
    w('# mode 0 = VLC (Huffman), mode 1 = CLC.  The index is (rounded value & QMASK[sel]); for')
    w('# selector 1 the index is (q0 & 3) * 4 + (q1 & 3) and one code covers a pair of values.')
    ptrs = u32s(0x4be9a8, 16)
    w('VLC = {')
    for sel in range(1, 8):
        for mode in range(2):
            p = ptrs[2 * sel + mode]
            if not p:
                continue
            n = 16 if sel == 1 else ([0, 16, 8, 8, 16, 16, 32, 64][sel])
            raw = u32s(p, 2 * n)
            align = 32 if (sel == 1 and mode == 0) else 24
            items = []
            for i in range(n):
                code, ln = raw[2 * i], raw[2 * i + 1]
                items.append('(%d, %d)' % (code >> (align - ln), ln))
            w('    (%d, %d): [%s],   # 0x%x' % (mode, sel, ', '.join(items), p))
    w('}')
    w('')
    w('# Scalar constants (float32 values unless noted)')
    consts = [('JS_K_SIDE', 0x48e8dc), ('JS_K_MATRIX', 0x48e8d8), ('JS_K_HYST', 0x48e8d4), ('JS_QUIET', 0x48e8d0),
              ('JS_RATIO_GAIN', 0x48e8b0), ('GC_FLOOR', 0x48e8f4), ('GC_MIN', 0x48e8ec), ('GC_RATIO', 0x48e8f0),
              ('GC_SQRT2', 0x48e8e8), ('GC_EXPSCALE', 0x48e8e4), ('GC_BAND0_MAX', 0x48e8e0), ('TONE_BEST_INIT', 0x48e8c8)]
    for n, a in consts:
        w('%s = %r   # 0x%x' % (n, float(f32s(a, 1)[0]), a))
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
