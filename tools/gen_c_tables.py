"""Generate src/tables.c from the Python reference models (spec/reference).

Every table of the C implementation comes from here, so the C build is bit-identical to the
models by construction and needs no libm for its tables.  float32 values are written as
decimal literals that round-trip exactly; bit-pattern tables stay as hex.

Usage:  .venv/bin/python tools/gen_c_tables.py            (rewrites src/tables.c)
"""
import os, sys, math
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'spec', 'reference'))

import at3_tables as dec            # noqa: E402
import lp2_tables as l2             # noqa: E402
import lp4_tables as l4             # noqa: E402
import atrac3_decoder as d3         # noqa: E402

out = []


def f32lit(v):
    v = float(np.float32(v))
    s = repr(v)
    if s in ('inf', '-inf', 'nan'):
        raise ValueError(v)
    if '.' not in s and 'e' not in s:
        s += '.0'
    return s + 'f'


def f64lit(v):
    s = repr(float(v))
    if '.' not in s and 'e' not in s:
        s += '.0'
    return s


def emit_array(ctype, name, vals, fmt, per_line=6, dims=None):
    """Emit a (possibly 2-D) C array definition."""
    vals = list(vals)
    if dims is None:
        decl = '%s %s[%d]' % (ctype, name, len(vals))
        rows = [vals]
    else:
        decl = '%s %s[%d][%d]' % (ctype, name, dims[0], dims[1])
        rows = [vals[i * dims[1]:(i + 1) * dims[1]] for i in range(dims[0])]
    out.append('const %s = {' % decl)
    for r in rows:
        if dims is not None:
            out.append('    {')
        items = [fmt(v) for v in r]
        ind = '        ' if dims is not None else '    '
        for i in range(0, len(items), per_line):
            out.append(ind + ', '.join(items[i:i + per_line]) + ',')
        if dims is not None:
            out.append('    },')
    out.append('};')
    out.append('')


def emit_scalar(ctype, name, lit):
    out.append('const %s %s = %s;' % (ctype, name, lit))


ihex = lambda v: '0x%08x' % (v & 0xffffffff)
idec = lambda v: '%d' % v


def code_table(name, table_of):
    """at3_code name[2][8][64]: (mode, sel) -> {code, len} by masked value index."""
    out.append('const at3_code %s[2][8][64] = {' % name)
    for mode in range(2):
        out.append('    {')
        for sel in range(8):
            tab = table_of(mode, sel)
            if not tab:
                out.append('        {{0, 0}},')
                continue
            items = ['{%d, %d}' % (c, l) for c, l in tab]
            out.append('        {')
            for i in range(0, len(items), 8):
                out.append('            ' + ', '.join(items[i:i + 8]) + ',')
            out.append('        },')
        out.append('    },')
    out.append('};')
    out.append('')


# ------------------------------------------------------------------ consistency checks
assert l2.SB_START == dec.SUBBAND_START == l4.SB_START
sf_from_bits = np.array(l4.SF_BITS, np.uint32).view(np.float32)
assert np.array_equal(l2.SF.view(np.uint32), sf_from_bits.view(np.uint32))
assert np.array_equal(np.array(dec.SF_TABLE, np.float32).view(np.uint32), sf_from_bits.view(np.uint32))
# Sony's LP4 tables equal the decoder-derived ones wherever the decoder defines a code
for (mode, sel), tab in l4.VLC.items():
    ref = l2.ENC_CODES[(mode, sel)]
    for idx, (c, l) in enumerate(tab):
        if ref[idx][1]:
            assert (c, l) == ref[idx], (mode, sel, idx)

# gain_window: float32(2 ** (k / 8)) for k = -176 .. 64, as computed by the LP2 model
POW2_8TH = [float(np.float32(math.pow(2.0, k * 0.125))) for k in range(-176, 65)]
# decoder gain interpolation: (2 ** (d / 8)) ** k for d = -15 .. 15, k = 0 .. 7
DEC_INC_POW = [(2.0 ** (d / 8.0)) ** k for d in range(-15, 16) for k in range(8)]

# ------------------------------------------------------------------ output
out.append('/* Generated by tools/gen_c_tables.py from spec/reference - do not edit. */')
out.append('#include "internal.h"')
out.append('')
out.append('/* ---------------------------------------------------------------- common */')
emit_array('int', 'at3_sb_start', l2.SB_START, idec, 11)
emit_array('float', 'at3_sf', l2.SF, f32lit, 4)
code_table('at3_codes', lambda m, s: l2.ENC_CODES.get((m, s)))
code_table('lp4_vlc', lambda m, s: l4.VLC.get((m, s)))

out.append('/* ---------------------------------------------------------------- LP2 encoder */')
emit_array('float', 'lp2_t1', l2.T1, f32lit, 4)
emit_array('float', 'lp2_qmf_win', l2.QMF_WIN, f32lit, 4)
emit_array('float', 'lp2_mdct_win', l2.MDCT_WIN, f32lit, 4)
emit_array('float', 'lp2_pre_cos', l2.PRE_COS, f32lit, 4)
emit_array('float', 'lp2_pre_sin', l2.PRE_SIN, f32lit, 4)
emit_array('float', 'lp2_fft_cos', l2.FFT_COS, f32lit, 4)
emit_array('float', 'lp2_fft_sin', l2.FFT_SIN, f32lit, 4)
emit_array('int', 'lp2_bitrev7', l2.BITREV7, idec, 16)
emit_array('float', 'lp2_post1', l2.POST1, f32lit, 4)
emit_array('float', 'lp2_post2', l2.POST2, f32lit, 4)
emit_array('float', 'lp2_post3', l2.POST3, f32lit, 4)
emit_array('float', 'lp2_post4', l2.POST4, f32lit, 4)
emit_array('float', 'lp2_pow2_8th', POW2_8TH, f32lit, 4)

out.append('/* ---------------------------------------------------------------- LP4 encoder */')
emit_array('int', 'lp4_is_joint', l4.IS_JOINT, idec, 8)
emit_array('int', 'lp4_bitrate', l4.BITRATE, idec, 8)
emit_array('int', 'lp4_block_align', l4.BLOCK_ALIGN, idec, 8)
emit_array('int', 'lp4_channel_bytes0', l4.CHANNEL_BYTES0, idec, 8)
emit_array('int', 'lp4_channel_bytes1', l4.CHANNEL_BYTES1, idec, 8)
emit_array('int', 'lp4_channel_hertz0', l4.CHANNEL_HERTZ0, idec, 8)
emit_array('int', 'lp4_channel_hertz1', l4.CHANNEL_HERTZ1, idec, 8)
emit_array('int', 'lp4_sb_width', l4.SB_WIDTH, idec, 16)
emit_array('float', 'lp4_qmf1', [v for r in l4.QMF1 for v in r], f32lit, 4, (12, 4))
emit_array('float', 'lp4_qmf2', [v for r in l4.QMF2 for v in r], f32lit, 4, (24, 4))
emit_array('int', 'lp4_mdct_perm', l4.MDCT_PERM, idec, 16)
emit_array('float', 'lp4_mdct_tw', [v for r in l4.MDCT_TW for v in r], f32lit, 4, (128, 4))
emit_array('float', 'lp4_mdct_fft_tw', l4.MDCT_FFT_TW, f32lit, 4)
emit_scalar('float', 'lp4_mdct_sqrt_half', f32lit(l4.MDCT_SQRT_HALF))
emit_array('float', 'lp4_gain_pow2', l4.GAIN_POW2, f32lit, 8)
emit_array('uint32_t', 'lp4_gain_ramp_bits', l4.GAIN_RAMP_BITS, ihex, 8)
emit_array('double', 'lp4_chsw_table', [float(np.float32(v)) for v in l4.CHSW_TABLE], f64lit, 8)
emit_array('double', 'lp4_chwt_table', [float(np.float32(v)) for v in l4.CHWT_TABLE], f64lit, 4)
emit_array('uint32_t', 'lp4_sf_bits', l4.SF_BITS, ihex, 8)
emit_array('uint32_t', 'lp4_qscale_bits', l4.QSCALE_BITS, ihex, 8)
emit_array('int', 'lp4_qmask', l4.QMASK, idec, 8)
emit_array('int', 'lp4_min_sfsum', l4.MIN_SFSUM, idec, 16)
emit_array('int', 'lp4_zero_len2', l4.ZERO_LEN2, idec, 8)
emit_array('int', 'lp4_step_cost', l4.STEP_COST, idec, 8)
emit_array('int', 'lp4_est_save', l4.EST_SAVE, idec, 8)
emit_array('int', 'lp4_est_bits', l4.EST_BITS, idec, 8)
emit_array('int', 'lp4_est_thr', l4.EST_THR, idec, 8)
emit_array('int', 'lp4_tone_penalty', l4.TONE_PENALTY, idec, 8)
emit_array('int', 'lp4_tone_sf_offset', l4.TONE_SF_OFFSET, idec, 16)
emit_array('int', 'lp4_sel1_len', l4.SEL1_LEN, idec, 16)
for name in ('JS_K_SIDE', 'JS_K_MATRIX', 'JS_K_HYST', 'JS_QUIET', 'JS_RATIO_GAIN', 'GC_FLOOR',
             'GC_MIN', 'GC_RATIO', 'GC_SQRT2', 'GC_EXPSCALE', 'GC_BAND0_MAX', 'TONE_BEST_INIT'):
    emit_scalar('double', 'lp4_' + name.lower(), f64lit(float(np.float32(getattr(l4, name)))))
out.append('')

out.append('/* ---------------------------------------------------------------- decoder */')
emit_array('double', 'dec_sf', d3.SF, f64lit, 4)
emit_array('double', 'dec_qmf_win', d3.QMF_WIN, f64lit, 4)
emit_array('double', 'dec_window', d3.WINDOW, f64lit, 4)
emit_array('double', 'dec_weights', [d3.WEIGHTS[i][j] for i in range(16) for j in range(2)],
           f64lit, 2, (16, 2))
emit_array('double', 'dec_inc_pow', DEC_INC_POW, f64lit, 4, (31, 8))

path = os.path.join(ROOT, 'src', 'tables.c')
with open(path, 'w') as f:
    f.write('\n'.join(out))
print('wrote', path)
